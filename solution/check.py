"""The scoreboard: runs the acceptance tests for each phase and explains every result in plain words. PROVIDED.

Raw test output is unreadable if you are not a programmer, and it would bury the one thing you need: which
requirement is not met yet. So this prints one line per phase, and for each failing test the requirement in plain
words BEFORE any technical detail. A phase whose files or functions you have not built yet says "not built yet",
never a crash. Passing it is the grade. Do not edit this file, and do not edit the tests.

What to look at
    PHASES          each phase: its title, its test module, and the names that must exist before it can run.
    run_phase()     runs one phase and prints each failure as "requirement" first, then "what happened".
    not_built()     the plain "not built yet" line: which file or which function is still missing.
    run_provided()  the provided files' own tests. They should always be green.
    run_style()     the comment standard for the files you build (every file tells its story, every function says why).

Usage:  python check.py            every phase          python check.py 2     one phase (or W7-2)
        python check.py style      the comment standard  python check.py extras  the stretch extras' tests
"""
import ast
import importlib
import os
import re
import sys
import unittest

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [ROOT, os.path.join(ROOT, "tests")]

BUILT_BY_YOU = ["state.py", "handoff.py", "planner.py", "executor.py", "supervisor.py", "workers.py", "reviewer.py",
                "prod.py", "graph.py"]
PHASES = [  # key, title, test module, the (module, name) pairs that must exist first
    ("W7-1", "State and one agent node", "test_phaseW7_1", [("state", "TeamState"), ("graph", "build_single")]),
    ("W7-2", "Planner and executor", "test_phaseW7_2", [("handoff", "make_handoff"), ("planner", "planner_node"),
                                                      ("executor", "executor_node"), ("graph", "build_two_agent")]),
    ("W7-3", "Break the handoff and cap it", "test_phaseW7_3", [("handoff", "validate_plan"), ("handoff", "MAX_CONTEXT_CHARS")]),
    ("W7-4", "Supervisor and workers", "test_phaseW7_4", [("supervisor", "supervisor_node"), ("workers", "worker_node"),
                                                        ("graph", "build_team")]),
    ("W7-6", "Reviewer on risky actions", "test_phaseW7_6", [("reviewer", "reviewer_node"), ("reviewer", "route_after_review")]),
    ("W7-7", "Cost meter and version stamp", "test_phaseW7_7", [("prod", "CostMeter"), ("prod", "version_stamp")]),
    ("W7-8", "The comparison (provided; runs your graphs)", "test_phaseW7_8", [("graph", "build_team"), ("prod", "CostMeter")]),
]


def short(text: str) -> str:
    """The line of a traceback that says what went wrong (the last 'SomethingError: ...' line), trimmed."""
    lines = [l for l in text.strip().splitlines() if l.strip()]
    errors = [l for l in lines if re.match(r"^[\w.]*(Error|Exception)\b", l)]
    return (errors[-1] if errors else lines[-1] if lines else "")[:260]


def not_built(key: str, title: str, needs: list) -> "str | None":
    """The plain 'not built yet' line when a file, a function or a package a phase needs is missing; else None."""
    for module_name, attr in needs:
        try:
            module = importlib.import_module(module_name)
        except ModuleNotFoundError as err:
            missing = (err.name or "").split(".")[0]
            if missing == "langgraph":
                return f"Phase {key}  {title}: LangGraph is not installed. Run:  pip install -r requirements.txt"
            if f"{missing}.py" in BUILT_BY_YOU:
                return f"Phase {key}  {title}: not built yet ({missing}.py does not exist)"
            return f"Phase {key}  {title}: cannot run yet (a Python package called '{missing}' is missing)"
        except Exception as err:   # a file that exists but does not import is not "not built": show why
            return f"Phase {key}  {title}: {module_name}.py does not import yet ({type(err).__name__}: {str(err)[:160]})"
        if not hasattr(module, attr):
            return f"Phase {key}  {title}: not built yet ({module_name}.{attr} does not exist)"
    return None


def run_phase(key: str, title: str, module_name: str, needs: list) -> bool:
    """Run one phase's tests and print its line. Returns True when it is fully green."""
    missing = not_built(key, title, needs)
    if missing:
        print(missing)
        return False
    module = importlib.import_module(module_name)
    suite = unittest.defaultTestLoader.loadTestsFromModule(module)
    problems, total = [], 0
    for group in suite:
        for test in group:
            total += 1
            result = unittest.TestResult()
            test.run(result)
            problems += [(test, trace) for _case, trace in result.failures + result.errors]
    if not problems:
        print(f"Phase {key}  {title}: all {total} green")
        return True
    print(f"Phase {key}  {title}: {total - len(problems)} of {total} green")
    for test, trace in problems:
        print(f"    Phase {key}, requirement: {(test.shortDescription() or test.id()).strip()}")
        print(f"        what happened: {short(trace)}")
    return False


def run_suite(label: str, module_name: str) -> bool:
    """Run a provided test module (the provided files, or the extras) and print one line."""
    suite = unittest.defaultTestLoader.loadTestsFromName(module_name)
    bad, total = [], suite.countTestCases()
    for group in suite:
        for test in group:
            result = unittest.TestResult()
            test.run(result)
            bad += [(test, t) for _c, t in result.failures + result.errors]
    if not bad:
        print(f"{label}: all {total} green")
        return True
    print(f"{label}: {total - len(bad)} of {total} green (do not edit these files)")
    for test, trace in bad:
        print(f"    requirement: {(test.shortDescription() or test.id()).strip()}\n        what happened: {short(trace)}")
    return False


def run_provided() -> bool:
    """The provided files' tests: config, llm, stand_in, desk_tools, gate, obs, baseline, data. Always green."""
    return run_suite("Setup   provided files", "test_provided")


def run_style() -> bool:
    """The comment standard: every file you built opens with a story, and every function and class has a docstring."""
    ok, seen = True, 0
    for filename in BUILT_BY_YOU:
        path = os.path.join(ROOT, filename)
        if not os.path.exists(path):
            continue
        seen += 1
        with open(path, encoding="utf-8") as handle:
            tree = ast.parse(handle.read())
        top = ast.get_docstring(tree) or ""
        missing = [] if top.count("\n\n") >= 2 else ["the file itself (open with a short story: what it is, why it is needed, what to look at)"]
        for item in ast.walk(tree):
            if isinstance(item, (ast.FunctionDef, ast.ClassDef)) and not ast.get_docstring(item):
                missing.append(f"{item.name} (line {item.lineno})")
        if missing:
            ok = False
            print(f"Style   {filename}: missing a docstring on: {', '.join(missing)}")
    if ok:
        print(f"Style   comment standard: ok ({seen} file{'s' if seen != 1 else ''} checked)")
    return ok


def main(argv: list) -> int:
    """Run what was asked for. Exit code 0 only when everything asked for is green."""
    want = (argv[0] if argv else "all").upper().replace("W7-", "").replace("W7_", "")
    keys = {p[0].replace("W7-", ""): p for p in PHASES}
    if want == "EXTRAS":
        return 0 if run_suite("Extras  stretch phases (W7-5, canary, monitor)", "extras.test_extras") else 1
    if want not in ("ALL", "STYLE", "0") and want not in keys:
        print("Usage: python check.py [1|2|3|4|6|7|8|style|extras]   (W7-1 ... also works)")
        return 2
    results = []
    if want == "0":
        return 0 if run_provided() else 1
    if want == "ALL":
        results.append(run_provided())
    for short_key, (key, title, module, needs) in keys.items():
        if want in ("ALL", short_key):
            results.append(run_phase(key, title, module, needs))
    if want in ("ALL", "STYLE"):
        results.append(run_style())
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
